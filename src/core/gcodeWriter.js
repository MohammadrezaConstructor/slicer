// Turns the sliced paths into G-code for a Marlin-style printer.
import { FEATURE, FEATURE_INFO } from './features.js';

const fmt = (v, d = 3) => {
  const s = v.toFixed(d);
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
};

/**
 * Cross-section of an extruded line. The nozzle squashes the plastic into a flat bead with
 * rounded sides: a rectangle (w − h) × h plus a circle of diameter h.
 */
export function beadArea(w, h) {
  return h < w ? (w - h) * h + (Math.PI * h * h) / 4 : w * h;
}

export function writeGcode(sl, S) {
  const out = [];
  const T = S.teachingComments;
  const c = (cmd, note) => out.push(T && note ? `${cmd} ; ${note}` : cmd);
  const filamentArea = Math.PI * (S.filamentDiameter / 2) ** 2;
  const flow = S.flow / 100;
  const w = S.lineWidth;

  let x = 0, y = 0, z = 0, e = 0, f = 0;
  let retracted = false, hopped = false, type = -1;

  const speedFor = (t, layer) => {
    if (layer === 0) return S.firstLayerSpeed;
    switch (t) {
      case FEATURE.OUTER: return S.outerWallSpeed;
      case FEATURE.INNER: return S.innerWallSpeed;
      case FEATURE.SKIN: return S.skinSpeed;
      case FEATURE.FILL: return S.infillSpeed;
      case FEATURE.SUPPORT: return S.supportSpeed;
      default: return S.firstLayerSpeed;
    }
  };
  const feed = (mmps) => {
    const F = Math.round(mmps * 60);
    if (F === f) return '';
    f = F;
    return ` F${F}`;
  };
  const retract = () => {
    if (retracted || !S.retraction || S.retractDistance <= 0) return;
    e -= S.retractDistance;
    out.push(`G1${feed(S.retractSpeed)} E${fmt(e, 5)}`);
    retracted = true;
    if (S.zHop > 0) {
      out.push(`G0${feed(S.travelSpeed)} Z${fmt(z + S.zHop)}`);
      hopped = true;
    }
  };
  const unretract = () => {
    if (hopped) {
      out.push(`G0${feed(S.travelSpeed)} Z${fmt(z)}`);
      hopped = false;
    }
    if (!retracted) return;
    e += S.retractDistance;
    out.push(`G1${feed(S.retractSpeed)} E${fmt(e, 5)}`);
    retracted = false;
  };
  const travel = (tx, ty, comb) => {
    const d = Math.hypot(tx - x, ty - y);
    if (d < 1e-4) return;
    const inside = S.combing && comb && segmentInside(comb, x, y, tx, ty);
    if (d > S.retractMinTravel && !inside) retract();
    out.push(`G0${feed(S.travelSpeed)} X${fmt(tx)} Y${fmt(ty)}`);
    x = tx;
    y = ty;
  };
  const extrudeTo = (tx, ty, ePerMm, speed) => {
    const d = Math.hypot(tx - x, ty - y);
    if (d < 1e-4) return;
    e += d * ePerMm;
    out.push(`G1${feed(speed)} X${fmt(tx)} Y${fmt(ty)} E${fmt(e, 5)}`);
    x = tx;
    y = ty;
  };

  // ---------------- start sequence ----------------
  out.push(';Generated by Slicer Lab (teaching slicer)');
  out.push(';FLAVOR:Marlin');
  out.push(`;LAYER_COUNT:${sl.layers.length}`);
  out.push(`;Settings: layer ${S.layerHeight} mm, line width ${w} mm, ${S.wallCount} walls, ${S.infillDensity}% ${S.infillPattern} infill, support ${S.support ? 'on' : 'off'}, ${S.material}`);
  if (T) out.push(';--- Start sequence: heat up, home, prime ---');
  c(`M140 S${S.bedTemp}`, 'start heating the bed (do not wait)');
  c(`M104 S${S.nozzleTemp}`, 'start heating the nozzle (do not wait)');
  c('G21', 'units are millimetres');
  c('G90', 'absolute positioning: X Y Z are coordinates on the bed');
  c('M82', 'absolute extrusion: E is the total length of filament pushed so far');
  c('G28', 'home all axes: move until the endstops are hit to find X=0 Y=0 Z=0');
  c(`M190 S${S.bedTemp}`, `wait until the bed reaches ${S.bedTemp} °C`);
  c(`M109 S${S.nozzleTemp}`, `wait until the nozzle reaches ${S.nozzleTemp} °C`);
  c('G92 E0', 'reset the extruder position to 0');
  c('M107', 'part cooling fan off');

  if (S.primeLine) {
    const ph = 0.3, pw = 0.8;
    const pe = beadArea(pw, ph) / filamentArea;
    const x1 = Math.min(S.bedX - 10, 120);
    out.push(';TYPE:PRIME');
    type = FEATURE.PRIME;
    if (T) out.push(';Prime line: push fresh plastic through the nozzle at the front of the bed');
    z = ph;
    out.push(`G0${feed(50)} Z${fmt(z)}`);
    out.push(`G0${feed(S.travelSpeed)} X10 Y3`);
    x = 10; y = 3;
    extrudeTo(x1, 3, pe, 25);
    extrudeTo(x1, 3.6, pe, 25);
    extrudeTo(10, 3.6, pe, 25);
    retract();
  }

  // ---------------- layers ----------------
  let fanValue = 0;
  for (let li = 0; li < sl.layers.length; li++) {
    const L = sl.layers[li];
    const ePerMm = (beadArea(w, L.h) * flow) / filamentArea;
    out.push(`;LAYER:${li}`);
    if (T && li === 0) out.push(';The first layer is printed slowly, without fan, so it sticks to the bed');

    // fan
    const fanTarget = li >= S.fanStartLayer - 1 ? S.fanSpeed : 0;
    if (fanTarget !== fanValue) {
      if (fanTarget > 0) c(`M106 S${Math.round((fanTarget / 100) * 255)}`, `part cooling fan at ${fanTarget}%`);
      else c('M107', 'fan off');
      fanValue = fanTarget;
    }

    // minimum layer time: slow down small layers so the plastic can cool before the next one
    let extTime = 0, travelDist = 0, px = x, py = y;
    for (const p of L.paths) {
      const sp = speedFor(p.type, li);
      travelDist += Math.hypot(p.pts[0] - px, p.pts[1] - py);
      const len = pathLength(p);
      extTime += len / sp;
      [px, py] = p.closed ? [p.pts[0], p.pts[1]] : [p.pts[p.pts.length - 2], p.pts[p.pts.length - 1]];
    }
    const travelTime = travelDist / S.travelSpeed;
    let slow = 1;
    if (li > 0 && S.minLayerTime > 0 && extTime > 0 && extTime + travelTime < S.minLayerTime) {
      slow = extTime / Math.max(0.1, S.minLayerTime - travelTime);
      if (T) out.push(`;Layer would take only ${(extTime + travelTime).toFixed(1)} s: slowing down to ${Math.round(slow * 100)}% for cooling`);
    }

    // move up to the new layer height
    retract();
    z = L.z;
    out.push(`G0${feed(S.travelSpeed)} Z${fmt(z)}`);

    for (const p of L.paths) {
      travel(p.pts[0], p.pts[1], L.comb);
      if (p.type !== type) {
        out.push(`;TYPE:${FEATURE_INFO[p.type].tag}`);
        type = p.type;
      }
      unretract();
      const speed = Math.max(Math.min(S.minSpeed, speedFor(p.type, li)), speedFor(p.type, li) * slow);
      const pts = p.pts;
      for (let k = 2; k < pts.length; k += 2) extrudeTo(pts[k], pts[k + 1], ePerMm, speed);
      if (p.closed) extrudeTo(pts[0], pts[1], ePerMm, speed);
    }
  }

  // ---------------- end sequence ----------------
  out.push(';TYPE:CUSTOM');
  if (T) out.push(';--- End sequence: retract, move away, switch everything off ---');
  retract();
  const zEnd = Math.min(S.bedZ, z + 10);
  c(`G0${feed(10)} Z${fmt(zEnd)}`, 'lift the nozzle away from the part');
  c(`G0${feed(S.travelSpeed)} X0 Y${fmt(S.bedY - 10)}`, 'move the head away and present the print');
  c('M104 S0', 'nozzle heater off');
  c('M140 S0', 'bed heater off');
  c('M107', 'fan off');
  c('M84', 'motors off');
  out.push(';End of print');
  return out.join('\n') + '\n';
}

function pathLength(p) {
  const a = p.pts;
  let len = 0;
  for (let k = 2; k < a.length; k += 2) len += Math.hypot(a[k] - a[k - 2], a[k + 1] - a[k - 1]);
  if (p.closed) len += Math.hypot(a[0] - a[a.length - 2], a[1] - a[a.length - 1]);
  return len;
}

/** Does the straight travel from (ax,ay) to (bx,by) stay inside the layer's outline? */
function segmentInside(loops, ax, ay, bx, by) {
  if (!loops.length) return false;
  const minX = Math.min(ax, bx), maxX = Math.max(ax, bx), minY = Math.min(ay, by), maxY = Math.max(ay, by);
  for (const L of loops) {
    const n = L.length;
    for (let i = 0; i < n; i += 2) {
      const cx = L[i], cy = L[i + 1], dx = L[(i + 2) % n], dy = L[(i + 3) % n];
      if (Math.max(cx, dx) < minX || Math.min(cx, dx) > maxX || Math.max(cy, dy) < minY || Math.min(cy, dy) > maxY) continue;
      if (segmentsCross(ax, ay, bx, by, cx, cy, dx, dy)) return false;
    }
  }
  return pointInLoops(loops, (ax + bx) / 2, (ay + by) / 2);
}

function segmentsCross(ax, ay, bx, by, cx, cy, dx, dy) {
  const d1 = (dx - cx) * (ay - cy) - (dy - cy) * (ax - cx);
  const d2 = (dx - cx) * (by - cy) - (dy - cy) * (bx - cx);
  const d3 = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
  const d4 = (bx - ax) * (dy - ay) - (by - ay) * (dx - ax);
  return d1 * d2 < 0 && d3 * d4 < 0;
}

/** Even-odd point-in-polygon test over all loops (outer contours and holes). */
export function pointInLoops(loops, px, py) {
  let inside = false;
  for (const L of loops) {
    const n = L.length;
    for (let i = 0, j = n - 2; i < n; j = i, i += 2) {
      const xi = L[i], yi = L[i + 1], xj = L[j], yj = L[j + 1];
      if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}
