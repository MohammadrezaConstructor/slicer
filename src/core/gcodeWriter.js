// Turns the sliced paths into G-code for a Marlin printer, the way PrusaSlicer does for the
// MK3S / Ender-3: machine limits in the header, the printer's own start/end code, relative
// extrusion (M83), per-feature speeds and accelerations, volumetric flow limit, cooling.
import { FEATURE, FEATURE_INFO } from './features.js';
import { PRINTER_PROFILES } from './printers.js';

const fmt = (v, d = 3) => {
  const s = v.toFixed(d);
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
};

/**
 * Cross-section of an extruded line. The nozzle squashes the plastic into a flat bead with
 * rounded sides: a rectangle (w − h) × h plus a circle of diameter h.
 */
export function beadArea(w, h) {
  return h < w ? (w - h) * h + (Math.PI * h * h) / 4 : w * h;
}

const SMALL_PERIMETER = 2 * Math.PI * 6.5; // loops shorter than this use the small-perimeter speed

export function pathLength(p) {
  const a = p.pts;
  let len = 0;
  for (let k = 2; k < a.length; k += 2) len += Math.hypot(a[k] - a[k - 2], a[k + 1] - a[k - 1]);
  if (p.closed) len += Math.hypot(a[0] - a[a.length - 2], a[1] - a[a.length - 1]);
  return len;
}

export function writeGcode(sl, S) {
  const prof = PRINTER_PROFILES[S.printer] || null;
  const out = [];
  const T = S.teachingComments;
  const c = (cmd, note) => out.push(T && note ? `${cmd} ; ${note}` : cmd);
  const filamentArea = Math.PI * (S.filamentDiameter / 2) ** 2;
  const flow = S.flow / 100;

  let x = 0, y = 0, z = 0, f = 0, accel = 0;
  let zNow = 0; // physical nozzle height (z plus any Z-hop)
  const moveZ = (target) => {
    if (Math.abs(target - zNow) < 1e-6) return;
    out.push(`G1 Z${fmt(target)}${feed(S.travelSpeed)}`);
    zNow = target;
  };
  let retracted = false, hopped = false, type = -1, fan = -1;

  const feed = (mmps) => {
    const F = Math.round(mmps * 60);
    if (F === f) return '';
    f = F;
    return ` F${F}`;
  };
  const setAccel = (a) => {
    a = Math.round(Math.min(a, S.maxPrintAccel));
    if (a !== accel) {
      out.push(`M204 S${a}`);
      accel = a;
    }
  };
  const setFan = (pct) => {
    const v = Math.round((pct / 100) * 255);
    if (v === fan) return;
    if (v > 0) c(`M106 S${v}`, `part cooling fan at ${pct}%`);
    else c('M107', 'fan off');
    fan = v;
  };
  const retract = () => {
    if (retracted || !S.retraction || S.retractDistance <= 0) return;
    out.push(`G1 E-${fmt(S.retractDistance, 5)}${feed(S.retractSpeed)}`);
    retracted = true;
    if (S.zHop > 0) {
      moveZ(z + S.zHop);
      hopped = true;
    }
  };
  const unretract = () => {
    if (hopped) {
      moveZ(z);
      hopped = false;
    }
    if (!retracted) return;
    out.push(`G1 E${fmt(S.retractDistance, 5)}${feed(S.retractSpeed)}`);
    retracted = false;
  };
  const travel = (tx, ty, comb) => {
    const d = Math.hypot(tx - x, ty - y);
    if (d < 1e-4) return;
    const inside = S.combing && comb && segmentInside(comb, x, y, tx, ty);
    if (d > S.retractMinTravel && !inside) retract();
    out.push(`G1 X${fmt(tx)} Y${fmt(ty)}${feed(S.travelSpeed)}`);
    x = tx;
    y = ty;
  };
  const extrudeTo = (tx, ty, ePerMm, speed) => {
    const d = Math.hypot(tx - x, ty - y);
    if (d < 1e-4) return;
    out.push(`G1 X${fmt(tx)} Y${fmt(ty)} E${fmt(d * ePerMm, 5)}${feed(speed)}`);
    x = tx;
    y = ty;
  };

  // ---------------- header ----------------
  const L0 = sl.layers[0];
  const bounds = firstLayerBounds(sl);
  out.push(`; generated by Slicer Lab (teaching slicer) for ${prof ? prof.label : 'a custom printer'}`);
  out.push(`; printer_model = ${prof ? prof.label : 'custom'}`);
  out.push(`;LAYER_COUNT:${sl.layers.length}`);
  out.push(`; layer ${S.layerHeight} mm, line width ${S.lineWidth} mm, ${S.wallCount} walls, ${S.infillDensity}% ${S.infillPattern} infill, support ${S.support ? 'on' : 'off'}, ${S.material}`);
  if (T) out.push('; --- Machine limits: the firmware never moves faster than this ---');
  c(`M201 X${S.maxAccelX} Y${S.maxAccelY} Z${S.maxAccelZ} E${S.maxAccelE}`, 'maximum accelerations, mm/s²');
  c(`M203 X${S.maxFeedX} Y${S.maxFeedY} Z${S.maxFeedZ} E${S.maxFeedE}`, 'maximum feed rates, mm/s');
  c(`M204 S${S.maxPrintAccel} T${S.retractAccel}`, 'acceleration (S) and retract acceleration (T), mm/s²');
  c(`M205 X${fmt(S.jerkX, 2)} Y${fmt(S.jerkY, 2)} Z${fmt(S.jerkZ, 2)} E${fmt(S.jerkE, 2)}`, 'jerk limits: instant speed changes, mm/s');
  c('M205 S0 T0', 'minimum extruding and travel feed rate');
  accel = S.maxPrintAccel;
  if (T) out.push('; --- Start sequence: heat up, home, level, prime ---');
  const tempS = { ...S, firstLayerNozzleTemp: S.firstLayerNozzleTemp, firstLayerBedTemp: S.firstLayerBedTemp };
  if (prof) out.push(...prof.start(tempS, bounds));
  else {
    out.push('G90 ; absolute coordinates', 'M83 ; relative extrusion: E is the filament for this move only');
    c(`M140 S${S.firstLayerBedTemp}`, 'start heating the bed');
    c(`M104 S${S.firstLayerNozzleTemp}`, 'start heating the nozzle');
    c('G28', 'home all axes');
    c(`M190 S${S.firstLayerBedTemp}`, 'wait for the bed');
    c(`M109 S${S.firstLayerNozzleTemp}`, 'wait for the nozzle');
    out.push('G1 Z0.3 F600', 'G1 X10 Y3 F6000', 'G92 E0', 'G1 X100 Y3 E12 F1200 ; prime line', 'G92 E0');
  }
  // position after the start code (only matters for the first retraction decision)
  const afterStart = S.printer === 'mk3s' ? [100, -3, 0.2] : S.printer === 'ender3' ? [2.3, 10, 0.28] : [100, 3, 0.3];
  [x, y, z] = afterStart;
  zNow = z;
  out.push('M107');
  fan = 0;
  if (T) out.push('; --- Print ---');

  // ---------------- layers ----------------
  let maxZ = 0;
  for (let li = 0; li < sl.layers.length; li++) {
    const L = sl.layers[li];
    maxZ = L.z;
    out.push(';LAYER_CHANGE', `;Z:${fmt(L.z)}`, `;HEIGHT:${fmt(L.h)}`, `;LAYER:${li}`);
    if (li === 1) {
      if (S.nozzleTemp !== S.firstLayerNozzleTemp) c(`M104 S${S.nozzleTemp}`, 'nozzle temperature for the rest of the print');
      if (S.bedTemp !== S.firstLayerBedTemp) c(`M140 S${S.bedTemp}`, 'bed temperature for the rest of the print');
    }
    const fanTarget = li >= S.fanOffLayers ? S.fanSpeed : 0;
    setFan(fanTarget);

    // speeds of every path (feature speed, small loops, flow limit, first layer)
    const speeds = L.paths.map((p) => pathSpeed(p, li, L.h, S));
    // Minimum layer time: if the layer would be printed too quickly, the plastic below is still
    // soft. Like PrusaSlicer, slow down the fastest lines first until all reach a common speed cap
    // (method of PrusaSlicer's CoolingBuffer.cpp, AGPL-3.0, Prusa Research / Slic3r — see
    // THIRD_PARTY_NOTICES.md; this implementation finds the cap by bisection).
    const lens = L.paths.map(pathLength);
    let fixedTime = 0, px = x, py = y;
    L.paths.forEach((p) => {
      const d = Math.hypot(p.pts[0] - px, p.pts[1] - py);
      fixedTime += d / S.travelSpeed;
      if (S.retraction && d > S.retractMinTravel) fixedTime += (2 * S.retractDistance) / S.retractSpeed + (2 * S.zHop) / S.maxFeedZ;
      [px, py] = p.closed ? [p.pts[0], p.pts[1]] : [p.pts[p.pts.length - 2], p.pts[p.pts.length - 1]];
    });
    const layerTime = (cap) => fixedTime + L.paths.reduce((t, p, i) => t + lens[i] / (p.bridge ? speeds[i] : Math.min(speeds[i], cap)), 0);
    let cap = Infinity;
    const t0 = layerTime(Infinity);
    if (li > 0 && S.minLayerTime > 0 && t0 < S.minLayerTime) {
      let lo = S.minSpeed, hi = Math.max(...speeds);
      if (layerTime(lo) <= S.minLayerTime) cap = lo;
      else {
        for (let k = 0; k < 40; k++) {
          const mid = (lo + hi) / 2;
          if (layerTime(mid) < S.minLayerTime) hi = mid;
          else lo = mid;
        }
        cap = lo;
      }
      if (T) out.push(`;Layer would take only ${t0.toFixed(1)} s: slowing down to max ${cap.toFixed(1)} mm/s for cooling`);
    }

    // move up to the new layer
    if (S.retractLayerChange) retract();
    z = L.z;
    hopped = retracted && S.zHop > 0;
    moveZ(z + (hopped ? S.zHop : 0));

    L.paths.forEach((p, i) => {
      travel(p.pts[0], p.pts[1], L.comb);
      if (p.type !== type) {
        out.push(`;TYPE:${FEATURE_INFO[p.type].tag}`);
        type = p.type;
      }
      if (p.bridge && T) out.push(';bridge: printed slowly over air with full cooling');
      setAccel(featureAccel(p, li, S));
      if (p.bridge) setFan(S.bridgeFan);
      unretract();
      const w = p.width || S.lineWidth;
      const ePerMm = (beadArea(w, L.h) * flow * (p.bridge ? 0.95 : 1)) / filamentArea;
      const speed = p.bridge ? speeds[i] : Math.min(speeds[i], cap);
      const pts = p.pts;
      for (let k = 2; k < pts.length; k += 2) extrudeTo(pts[k], pts[k + 1], ePerMm, speed);
      if (p.closed) extrudeTo(pts[0], pts[1], ePerMm, speed);
      if (p.bridge) setFan(fanTarget);
    });
  }

  // ---------------- end sequence ----------------
  out.push(';TYPE:CUSTOM');
  if (T) out.push('; --- End sequence: retract, move away, switch everything off ---');
  retract();
  if (prof) out.push(...prof.end(S, maxZ + (hopped ? S.zHop : 0)));
  else {
    out.push(`G1 Z${fmt(Math.min(S.bedZ, maxZ + 10))} F600 ; lift`, `G1 X0 Y${fmt(S.bedY - 10)} F6000 ; present the print`);
    out.push('M104 S0 ; nozzle heater off', 'M140 S0 ; bed heater off', 'M107 ; fan off', 'M84 ; motors off');
  }
  out.push(';End of print');
  return out.join('\n') + '\n';
}

/** Speed (mm/s) of a path before the cooling slow-down. */
export function pathSpeed(p, li, h, S) {
  let v;
  switch (p.type) {
    case FEATURE.OUTER: v = S.outerWallSpeed; break;
    case FEATURE.INNER: v = S.innerWallSpeed; break;
    case FEATURE.SKIN: v = p.bridge ? S.bridgeSpeed : p.top ? S.topSkinSpeed : S.skinSpeed; break;
    case FEATURE.FILL: v = S.infillSpeed; break;
    case FEATURE.SUPPORT: v = S.supportSpeed; break;
    default: v = S.firstLayerSpeed;
  }
  if ((p.type === FEATURE.OUTER || p.type === FEATURE.INNER) && p.closed && pathLength(p) < SMALL_PERIMETER) v = Math.min(v, S.smallPerimeterSpeed);
  if (li === 0) v = Math.min(v, S.firstLayerSpeed);
  // the hot end can only melt so much plastic per second
  const area = beadArea(p.width || S.lineWidth, h);
  if (S.maxVolumetric > 0) v = Math.min(v, S.maxVolumetric / area);
  return v;
}

function featureAccel(p, li, S) {
  if (li === 0) return S.firstLayerAccel;
  if (p.bridge) return S.bridgeAccel;
  if (p.type === FEATURE.OUTER || p.type === FEATURE.INNER) return S.wallAccel;
  if (p.type === FEATURE.FILL || p.type === FEATURE.SKIN) return S.infillAccel;
  return S.defaultAccel;
}

function firstLayerBounds(sl) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const p of sl.layers[0]?.paths || []) {
    if (p.type === FEATURE.SKIRT) continue;
    for (let i = 0; i < p.pts.length; i += 2) {
      minX = Math.min(minX, p.pts[i]); maxX = Math.max(maxX, p.pts[i]);
      minY = Math.min(minY, p.pts[i + 1]); maxY = Math.max(maxY, p.pts[i + 1]);
    }
  }
  if (!isFinite(minX)) return { minX: 0, minY: 0, maxX: 10, maxY: 10 };
  return { minX, minY, maxX, maxY };
}

/** Does the straight travel from (ax,ay) to (bx,by) stay inside the layer's outline? */
export function segmentInside(loops, ax, ay, bx, by) {
  if (!loops.length) return false;
  const minX = Math.min(ax, bx), maxX = Math.max(ax, bx), minY = Math.min(ay, by), maxY = Math.max(ay, by);
  for (const L of loops) {
    const n = L.length;
    for (let i = 0; i < n; i += 2) {
      const cx = L[i], cy = L[i + 1], dx = L[(i + 2) % n], dy = L[(i + 3) % n];
      if (Math.max(cx, dx) < minX || Math.min(cx, dx) > maxX || Math.max(cy, dy) < minY || Math.min(cy, dy) > maxY) continue;
      if (segmentsCross(ax, ay, bx, by, cx, cy, dx, dy)) return false;
    }
  }
  return pointInLoops(loops, (ax + bx) / 2, (ay + by) / 2);
}

function segmentsCross(ax, ay, bx, by, cx, cy, dx, dy) {
  const d1 = (dx - cx) * (ay - cy) - (dy - cy) * (ax - cx);
  const d2 = (dx - cx) * (by - cy) - (dy - cy) * (bx - cx);
  const d3 = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
  const d4 = (bx - ax) * (dy - ay) - (by - ay) * (dx - ax);
  return d1 * d2 < 0 && d3 * d4 < 0;
}

/** Even-odd point-in-polygon test over all loops (outer contours and holes). */
export function pointInLoops(loops, px, py) {
  let inside = false;
  for (const L of loops) {
    const n = L.length;
    for (let i = 0, j = n - 2; i < n; j = i, i += 2) {
      const xi = L[i], yi = L[i + 1], xj = L[j], yj = L[j + 1];
      if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

/**
 * After the time estimate is known, add progress lines (M73: percent done and minutes
 * remaining, shown on the printer's display) and summary comments, like PrusaSlicer does.
 */
export function addProgressInfo(gcode, P, S) {
  const total = P.stats.time;
  const lines = gcode.split('\n');
  const atLine = new Map();
  for (const L of P.layers) {
    const m = L.first;
    if (m < P.n) atLine.set(P.line[m], P.t0[m]);
  }
  const out = [];
  let startDone = false;
  for (let i = 0; i < lines.length; i++) {
    if (!startDone && lines[i].startsWith('M201')) {
      out.push(`M73 P0 R${Math.round(total / 60)} ; progress: 0% done, ${Math.round(total / 60)} min remaining`);
      startDone = true;
    }
    if (lines[i].startsWith(';LAYER_CHANGE')) {
      // find the time of the next move belonging to this layer
      let t = null;
      for (let k = i; k < Math.min(lines.length, i + 12) && t === null; k++) if (atLine.has(k)) t = atLine.get(k);
      if (t !== null) out.push(`M73 P${Math.floor((t / total) * 100)} R${Math.round((total - t) / 60)}`);
    }
    out.push(lines[i]);
  }
  const grams = ((P.stats.filament * Math.PI * (S.filamentDiameter / 2) ** 2) / 1000) * S.filamentDensity;
  const hms = (s) => `${Math.floor(s / 3600) ? Math.floor(s / 3600) + 'h ' : ''}${Math.floor((s % 3600) / 60)}m ${Math.round(s % 60)}s`;
  out.push(
    `; filament used [mm] = ${P.stats.filament.toFixed(2)}`,
    `; filament used [g] = ${grams.toFixed(2)}`,
    `; total filament cost = ${((grams / 1000) * S.filamentCost).toFixed(2)}`,
    `; estimated printing time (normal mode) = ${hms(P.stats.motionTime)}`,
    `; estimated total time incl. heating and homing = ${hms(total)}`,
  );
  return out.join('\n');
}
